"""Build flat-file baselines, tokenize them and the captured graph responses, write results/REPORT.md.

Run: Benchmark/.venv/Scripts/python.exe Benchmark/measure.py
"""
import json
import re
import subprocess
from pathlib import Path

import tiktoken

HERE = Path(__file__).parent
ROOT = HERE.parent
OUT = HERE / "results"
ENCS = {n: tiktoken.get_encoding(n) for n in ("o200k_base", "cl100k_base")}


def run(argv):
    return subprocess.run(argv, cwd=ROOT, capture_output=True, text=True, encoding="utf-8", errors="replace").stdout


def read_lines(rel):
    return (ROOT / rel).read_text(encoding="utf-8", errors="replace").splitlines()


def merge_spans(nums, ctx, total):
    spans = []
    for n in sorted(nums):
        lo, hi = max(1, n - ctx), min(total, n + ctx)
        if spans and lo <= spans[-1][1] + 1:
            spans[-1][1] = max(spans[-1][1], hi)
        else:
            spans.append([lo, hi])
    return spans


def baseline(b):
    if b.get("cmd"):
        return run(b["cmd"])
    paths = b["paths"]
    if b["mode"] == "head":
        files = run(["git", "ls-files", "--"] + paths).split()
        return "".join(f"== {f}\n" + "\n".join(read_lines(f)[: b["head"]]) + "\n" for f in files)
    flags = ["-n", "-E"] + (["-i"] if b.get("ignore_case") else [])
    text, hits = "", {}
    for rx in b["grep"]:
        r = subprocess.run(["git", "grep"] + flags + [rx, "--"] + paths, cwd=ROOT, capture_output=True, text=True, encoding="utf-8", errors="replace")
        if r.returncode > 1:
            raise SystemExit(f"git grep failed for {rx!r}: {r.stderr.strip()}")
        out = r.stdout
        text += out
        for ln in out.splitlines():
            m = re.match(r"^(.*?):(\d+):", ln)
            if m:
                hits.setdefault(m.group(1), set()).add(int(m.group(2)))
    for f, nums in sorted(hits.items()):
        lines = read_lines(f)
        if b["mode"] == "whole":
            text += f"== {f}\n" + "\n".join(lines) + "\n"
            continue
        for lo, hi in merge_spans(nums, b["ctx"], len(lines)):
            text += f"== {f}:{lo}-{hi}\n" + "\n".join(lines[lo - 1 : hi]) + "\n"
    return text


def counts(text):
    return {**{n: len(e.encode(text)) for n, e in ENCS.items()}, "chars_div4": len(text) // 4}


def pct(b, g):
    return f"{(b - g) / b * 100:.0f}%" if b else "-"


def main():
    (OUT / "baseline").mkdir(parents=True, exist_ok=True)
    tasks = json.loads((HERE / "tasks.json").read_text(encoding="utf-8"))
    rows = []
    for t in tasks:
        base = baseline(t["baseline"])
        (OUT / "baseline" / f"{t['id']}.txt").write_text(base, encoding="utf-8")
        gp = OUT / "graph" / t["graph_file"]
        graph = gp.read_text(encoding="utf-8") if gp.exists() else None
        rows.append({"id": t["id"], "name": t["name"], "baseline": counts(base),
                     "graph": counts(graph) if graph is not None else None})
    (OUT / "results.json").write_text(json.dumps(rows, indent=2), encoding="utf-8")

    lines = ["# Benchmark report (generated by measure.py)", "",
             "Counts use tiktoken (`o200k_base`, `cl100k_base`). Claude's tokenizer is not public, so these are a proxy; `chars_div4` is the old estimate for comparison.", ""]
    for enc in (*ENCS, "chars_div4"):
        lines += [f"## {enc}", "", "| Task | Baseline | Graph | Saved | % saved |", "|---|---:|---:|---:|---:|"]
        tb = tg = 0
        for r in rows:
            b = r["baseline"][enc]
            if r["graph"] is None:
                lines.append(f"| {r['name']} | {b:,} | n/a | n/a | n/a |")
                continue
            g = r["graph"][enc]
            tb, tg = tb + b, tg + g
            lines.append(f"| {r['name']} | {b:,} | {g:,} | {b - g:,} | {pct(b, g)} |")
        lines += [f"| **Total** | **{tb:,}** | **{tg:,}** | **{tb - tg:,}** | **{pct(tb, tg)}** |", ""]
    (OUT / "REPORT.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
